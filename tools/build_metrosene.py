"""Build js/threads-metrosene.js from Mettler's Metrosene product page.

Mettler publishes the Metrosene colour range (number + name) on
https://www.amann-mettler.com/en/products/detail/metrosene/ , each with a small
photo of the thread wound on a spool. There is no published RGB value, so the
screen colour is estimated from that photo: the middle of the picture is
averaged in linear light, ignoring the darkest and brightest 12 % of pixels
(shadows between the windings and shiny highlights).

Steps (macOS; `sips` converts the JPEG swatches to BMP, which Python can read):

    mkdir -p work/img work/bmp
    curl -sL -o work/metrosene.html https://www.amann-mettler.com/en/products/detail/metrosene/
    # download every swatch URL listed in the page into work/img/_<code>.jpg
    # (the swatch for 0075x lives at _0075.jpg), then:
    for f in work/img/*.jpg; do sips -s format bmp "$f" --out "work/bmp/$(basename "$f" .jpg).bmp"; done
    python3 -I tools/build_metrosene.py work/metrosene.html work/bmp > js/threads-metrosene.js
"""
import html
import json
import os
import re
import struct
import sys


def read_bmp(path):
    """Return (width, height, rows of (r, g, b)) for an uncompressed 24/32-bit BMP."""
    with open(path, "rb") as f:
        data = f.read()
    if data[:2] != b"BM":
        raise ValueError("not a BMP: " + path)
    offset = struct.unpack_from("<I", data, 10)[0]
    width, height = struct.unpack_from("<ii", data, 18)
    bpp = struct.unpack_from("<H", data, 28)[0]
    compression = struct.unpack_from("<I", data, 30)[0]
    if bpp not in (24, 32) or compression not in (0, 3):
        raise ValueError("unsupported BMP format: %s" % path)
    top_down = height < 0
    height = abs(height)
    step = bpp // 8
    stride = (width * step + 3) & ~3
    rows = []
    for y in range(height):
        src_y = y if top_down else height - 1 - y
        base = offset + src_y * stride
        row = []
        for x in range(width):
            b, g, r = data[base + x * step: base + x * step + 3]
            row.append((r, g, b))
        rows.append(row)
    return width, height, rows


def to_linear(c):
    c /= 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def from_linear(c):
    c = max(0.0, min(1.0, c))
    v = 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055
    return round(v * 255)


def swatch_colour(path, margin=0.15, trim=0.12):
    w, h, rows = read_bmp(path)
    x0, x1 = int(w * margin), int(w * (1 - margin))
    y0, y1 = int(h * margin), int(h * (1 - margin))
    px = []
    for y in range(y0, y1):
        for x in range(x0, x1):
            r, g, b = rows[y][x]
            lr, lg, lb = to_linear(r), to_linear(g), to_linear(b)
            px.append((0.2126 * lr + 0.7152 * lg + 0.0722 * lb, lr, lg, lb))
    px.sort()
    k = int(len(px) * trim)
    kept = px[k: len(px) - k] or px
    n = len(kept)
    r = sum(p[1] for p in kept) / n
    g = sum(p[2] for p in kept) / n
    b = sum(p[3] for p in kept) / n
    return "#%02X%02X%02X" % (from_linear(r), from_linear(g), from_linear(b))


def main():
    page, bmp_dir = sys.argv[1], sys.argv[2]
    text = open(page, encoding="utf-8", errors="replace").read()
    entries = re.findall(
        r'data-colorcode="([^"]+)"\s*data-colorname="([^"]*)"', text)
    seen, rows = set(), []
    for raw_code, name in entries:
        if raw_code in seen:
            continue
        seen.add(raw_code)
        code = raw_code.rstrip("x")  # Mettler marks some numbers with a trailing x
        path = os.path.join(bmp_dir, "_%s.bmp" % raw_code)
        if not os.path.exists(path):
            print("missing swatch for %s" % raw_code, file=sys.stderr)
            continue
        rows.append([code, " ".join(html.unescape(name).split()), swatch_colour(path)])

    codes = [r[0] for r in rows]
    assert len(codes) == len(set(codes)), "duplicate colour numbers"

    out = [
        "// Generated by tools/build_metrosene.py — do not edit by hand.",
        "// Mettler METROSENE all-purpose sewing thread: colour numbers and names from",
        "// amann-mettler.com; screen colours estimated from Mettler's swatch photos.",
        "// Order follows Mettler's colour selector (families grouped together).",
        "(function (F) {",
        "  F.threadLibraries = F.threadLibraries || {};",
        "  F.threadLibraries.Metrosene = {",
        "    name: 'Mettler Metrosene',",
        "    brand: 'Metrosene',",
        "    colors: [",
    ]
    for code, name, hx in rows:
        out.append("      [%s, %s, %s]," % (json.dumps(code), json.dumps(name), json.dumps(hx)))
    out += ["    ],", "  };", "})(window.Fabrica = window.Fabrica || {});", ""]
    sys.stdout.write("\n".join(out))
    print("%d colours" % len(rows), file=sys.stderr)


if __name__ == "__main__":
    main()
