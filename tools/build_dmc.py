"""Build js/threads-dmc.js from the DMC floss CSV.

Source data: https://github.com/sharlagelfand/dmc (MIT), which in turn took it
from https://github.com/adrianj/CrossStitchCreator. The fixes below mirror the
cleaning in that repo's data-raw/floss.R.

Usage: python3 -I tools/build_dmc.py path/to/floss_adrianj.csv > js/threads-dmc.js
"""
import csv, json, re, sys

HEX_FIX = {"221": "883E43", "910": "187E56", "699": "056517", "869": "835E39",
           "310": "000000", "434": "985E33"}
RGB_FIX = {"309": "BA4A4A", "3609": "F4AED5", "225": "FFDFD5", "210": "C39FC3",
           "3755": "93B4CE", "3849": "52B3AE", "3848": "419392", "890": "174923",
           "3830": "B95544"}
NAME_FIX = {"666": "Red - Bright", "3846": "Turquoise - Light Bright",
            "3845": "Turquoise - Medium Bright", "3844": "Turquoise - Dark Bright",
            "311": "Navy Blue - Medium", "943": "Aquamarine - Medium",
            "890": "Pistachio Green - Ultra Dark", "934": "Avocado Green - Black",
            "966": "Baby Green - Medium", "561": "Jade - Very Dark",
            "608": "Orange - Bright", "407": "Desert Sand - Dark",
            "3773": "Desert Sand - Medium"}
ABBR = [("Ult", "Ultra"), ("Vy", "Very"), ("Dk", "Dark"), ("Med", "Medium"),
        ("Lt", "Light"), ("Vry", "Very"), ("Md", "Medium"), ("M", "Medium"),
        ("V", "Very"), ("D", "Dark"), ("VD", "Very Dark"), ("VyDk", "Very Dark"),
        ("Grn", "Green"), ("Brn", "Brown"), ("U", "Ultra")]
SUFFIXES = ["Ultra Very Light", "Ultra Very Dark", "Medium Very Light",
            "Medium Very Dark", "Medium Light", "Medium Dark", "Ultra Light",
            "Ultra Pale", "Ultra Dark", "Very Light", "Very Dark"]
END_SUFFIXES = ["Pale Light", "Light", "Pale", "Medium", "Dark", "Bright", "Deep"]


def clean_name(name):
    name = " ".join(name.split())
    for a, b in ABBR:
        name = re.sub(r"\b%s\b" % re.escape(a), b, name)
    name = name.replace("?", " ")
    name = " ".join(name.split())
    for s in SUFFIXES:
        if s in name:
            return name.replace(s, "- " + s, 1)
    for s in END_SUFFIXES:
        if name.endswith(s) and name != s:
            return name[: -len(s)] + "- " + s
    return name


rows = []
with open(sys.argv[1], newline="", encoding="utf-8-sig") as f:
    for r in csv.DictReader(f):
        code = r["Floss#"].strip()
        hx = RGB_FIX.get(code) or HEX_FIX.get(code) or r["RGB code"].strip()
        hx = hx.upper().zfill(6)
        assert re.fullmatch(r"[0-9A-F]{6}", hx), (code, hx)
        name = NAME_FIX.get(code) or clean_name(r["Description"])
        rows.append([code, name, "#" + hx])

out = ["// Generated by tools/build_dmc.py — do not edit by hand.",
       "// DMC six-strand embroidery floss colours (approximate screen colours).",
       "// Data: github.com/sharlagelfand/dmc (MIT), from github.com/adrianj/CrossStitchCreator.",
       "// Order follows the physical DMC colour card (families grouped together).",
       "(function (F) {",
       "  F.threadLibraries = F.threadLibraries || {};",
       "  F.threadLibraries.DMC = {",
       "    name: 'DMC Stranded Cotton',",
       "    brand: 'DMC',",
       "    colors: ["]
for code, name, hx in rows:
    out.append("      [%s, %s, %s]," % (json.dumps(code), json.dumps(name), json.dumps(hx)))
out += ["    ],", "  };", "})(window.Fabrica = window.Fabrica || {});", ""]
sys.stdout.write("\n".join(out))
print("%d colours" % len(rows), file=sys.stderr)
